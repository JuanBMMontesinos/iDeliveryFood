-- Honest Channel Statuses, Realtime Cursor Sequence & RLS Update Policy

BEGIN;

-- 1. Enrich public.outbox_events with max_attempts, processed_at, and retryable status check
ALTER TABLE public.outbox_events
  ADD COLUMN IF NOT EXISTS max_attempts integer NOT NULL DEFAULT 5 CHECK (max_attempts >= 1),
  ADD COLUMN IF NOT EXISTS processed_at timestamptz;

ALTER TABLE public.outbox_events
  DROP CONSTRAINT IF EXISTS outbox_events_status_check;

ALTER TABLE public.outbox_events
  ADD CONSTRAINT outbox_events_status_check
  CHECK (status IN ('PENDING', 'PROCESSING', 'PUBLISHED', 'COMPLETED', 'FAILED', 'DEAD_LETTER'));

CREATE INDEX IF NOT EXISTS idx_outbox_events_poll
  ON public.outbox_events(status, next_attempt_at ASC, created_at ASC)
  WHERE status IN ('PENDING', 'FAILED');

-- 2. Enrich public.notification_deliveries with versioned templates, category, localized title/body,
--    idempotency key, and monotonic cursor_seq for Realtime catch-up recovery
ALTER TABLE public.notification_deliveries
  ADD COLUMN IF NOT EXISTS template_version integer NOT NULL DEFAULT 1 CHECK (template_version >= 1),
  ADD COLUMN IF NOT EXISTS category text NOT NULL DEFAULT 'TRANSACTIONAL'
    CHECK (category IN ('TRANSACTIONAL', 'SECURITY', 'MARKETING')),
  ADD COLUMN IF NOT EXISTS title text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS body text NOT NULL DEFAULT '',
  ADD COLUMN IF NOT EXISTS payload jsonb NOT NULL DEFAULT '{}'::jsonb,
  ADD COLUMN IF NOT EXISTS idempotency_key text UNIQUE,
  ADD COLUMN IF NOT EXISTS cursor_seq bigint GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN IF NOT EXISTS last_error text;

ALTER TABLE public.notification_deliveries
  DROP CONSTRAINT IF EXISTS notification_deliveries_channel_check;

ALTER TABLE public.notification_deliveries
  ADD CONSTRAINT notification_deliveries_channel_check
  CHECK (channel IN ('IN_APP', 'PUSH', 'PUSH_ANDROID', 'PUSH_IOS', 'EMAIL', 'WEBHOOK'));

ALTER TABLE public.notification_deliveries
  DROP CONSTRAINT IF EXISTS notification_deliveries_status_check;

ALTER TABLE public.notification_deliveries
  ADD CONSTRAINT notification_deliveries_status_check
  CHECK (
    status IN (
      'QUEUED',
      'SENT_TO_PROVIDER',
      'DELIVERED',
      'BLOCKED_MISSING_CREDENTIALS',
      'SKIPPED_OPT_OUT',
      'BLOCKED_DEVICE_REVOKED',
      'FAILED'
    )
  );

CREATE UNIQUE INDEX IF NOT EXISTS idx_notification_deliveries_outbox_channel_recipient
  ON public.notification_deliveries(outbox_event_id, channel, recipient_user_id)
  WHERE outbox_event_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_notification_deliveries_cursor
  ON public.notification_deliveries(recipient_user_id, cursor_seq ASC);

-- 3. Allow authenticated users to mark their own notifications as read
DO $$ BEGIN
  CREATE POLICY notification_deliveries_update_own_read ON public.notification_deliveries
    FOR UPDATE TO authenticated
    USING (recipient_user_id = (SELECT auth.uid()))
    WITH CHECK (recipient_user_id = (SELECT auth.uid()));
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- 4. Ensure public.notification_deliveries is published to Supabase Realtime
DO $$ BEGIN
  ALTER PUBLICATION supabase_realtime ADD TABLE public.notification_deliveries;
EXCEPTION WHEN duplicate_object OR undefined_object THEN NULL; END $$;

COMMIT;
